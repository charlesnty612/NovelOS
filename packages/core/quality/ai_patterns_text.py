"""最小判定长度与段切分口径（V4.0 模块化拆分自 ai_patterns.py，2026-09-30）。

只放**多族共用**的口径单点：

- ``_split_paragraphs``：段级三条算子 + 对白配对共用（``\n+``，口径不得分叉）；
- ``_MIN_PROSE_CHARS_FOR_DENSITY``：密度类算子的最小判定正文长度（句式 / 段落 / 回声族共用）；
- ``_MIN_PROSE_CHARS_FOR_READABILITY``：可读性类算子的最小判定长度（长段 / 对白可见字共用）。

独立成模块而非并入任一族：三个族都要 import 本模块，若并入其中一族则其余族要
反向依赖，多族互相 import 即成环。
"""
from __future__ import annotations

import re

# 两条可读性规则的**最小判定长度**（照 _MIN_PROSE_CHARS_FOR_DENSITY 先例）：
# 短片段（单测样例、引文、题记）没有排版/配比的统计意义，一律不判。
# 生产章节目标 3000 字、带宽下限 1200，落在守卫之上不受影响。
_MIN_PROSE_CHARS_FOR_READABILITY = 600

# ---------------------------------------------------------------------------
# 段切分口径（本模块**唯一**入口，三条段级算子共用）
# ---------------------------------------------------------------------------
# 按**任意换行序列**切段（``\n+``）。
#
# 为什么是 ``\n+`` 而不是 ``\n\n``（2026-09-27 复算实证）：文风锚点书等外部语料
# 是**一行一段**，榜一侯府弧 19 章的 ``\n\n`` 总数 = **0**。用 ``\n\n`` 切分会把
# 19 章读成 **19 个整章大段**（每段远超 12 字上限），于是段切分类算子在人类语料上
# **构造上不可能命中**——``AI-SHORT-PARA`` 此前登记的「人类基线 0.00/千字」不是测
# 出来的，是量具口径造成的假象。改用 ``\n+`` 后人类侧立刻出现 10 处命中。
# 本仓生成侧两口径只差 5 段（3479 → 3484，个别章存在单换行），所以口径统一对
# 生成侧几乎无影响、对人类侧是「从假象变回可测」。
#
# 短段 / 长段 / 相邻对白三条段级算子一律走本函数：口径分叉过一次就出过「人类基线是
# 量具假象」的事故，本批把段级三条收敛到同一入口。
#
# ✅ **本函数现已是全模块唯一的段切分入口**（2026-10-15 批次（六）G8 收口）。
# 此前 :func:`_last_paragraph`（``AI-ENDING-SUMMARY`` 专用，拆分时随门面留在
# ``ai_patterns.py``）仍内联**第二份独立的段落切分实现**，2026-09-27 起挂着「已登记
# 为待修」；本批把它也收敛到这里，触发条件（生产 draft 出现 CRLF 或单换行形态时
# 它会把整章当末段扫）随口径统一一并消除。
# 实测：人类锚点书 19 章 ``\n\n`` 总数为 0 ⇒ 旧实现在该语料上返回的「末段」比整章
# 可见字还长（比值下界 1.0163 > 1）；收敛后为真末段（比值上界 0.0533）。
# 判别：tests/unit/quality/test_readability_rules.py 的形状级断言现已要求
# **内联切分出现处为 0**（原为 1，即把该缺陷写成了期望值——2026-10-15 订正），
# 另配一条正向断言要求 ``_last_paragraph`` 确实调用本函数（防「删掉函数」也算过）。
# 本注释与门面 docstring 一律**不复述那个字面**，复述会被断言一并计入而突然变红。
def _split_paragraphs(prose: str) -> list[str]:
    return [p.strip() for p in re.split(r"\n+", prose) if p.strip()]
# 密度类规则的**最小判定长度**：几十字的字符串（单测样例、片段）算密度没有统计意义，
# 「1 处命中 / 17 字 = 58/千字」会稳定误报。低于此长度一律不判密度。
_MIN_PROSE_CHARS_FOR_DENSITY = 200
