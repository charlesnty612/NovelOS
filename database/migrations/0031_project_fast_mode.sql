-- NovelOS Database Migration 0031: projects.fast_mode（项目级「快通道」开关）
--
-- 背景（性能诉求，2026-10-14）：
--   写一章到定稿要过 4 个 workflow run + 2 次人工审批往返 + 最多 2 轮自动改稿，
--   最多 11 次 LLM 调用，单章十几分钟。作者要求「拆掉所有闸门，写完直接提交」。
--   逐环节核对后确认耗时与卡点分布（见 AGENTS.md §二 快通道条目）：
--     - chapter-review 整条链（critic + deep_reviewer 2 次 LLM + author_review
--       人工 PAUSE）是最大的一块，且其驳回还会触发自动改稿回路（每轮又是
--       write + review，最多再 +10 次 LLM）；
--     - chapter-commit 的 quality_gate 阻断与 high_risk_approval 人工 PAUSE；
--     - **observer 不在 review 里而在 commit 里**，它是唯一抽出角色目标推进 /
--       伏笔收放 / 世界观 delta 并写 story_state 的节点 ⇒ **快通道保留它**，
--       砍掉会导致后续章节失忆。
--
-- 列语义：
--   - `fast_mode`：**INTEGER 可空三态**，NULL = 未设置（走默认关）。
--       1 / 0 为作者显式选择。之所以用可空三态而非 NOT NULL DEFAULT 0，是要与
--       0023 `word_band_json` / 0029 `writing_bible` 同款——「无覆盖」与「显式关闭」
--       必须可区分，否则将来改默认值时无法与作者既有选择区分。
--   - 优先级（单点解析见 `packages/core/api/routers/workflows/fast_mode.py`）：
--       请求体 StartWorkflowRequest.fast_mode > 本列 > env NOVELOS_FAST_MODE > 关。
--   - 语义范围：只影响**闸门是否阻断/是否挂起等人工**，**不影响**任何状态更新
--       （observer / inject_validate / commit_delta 全部照跑）。它是「关闸门」
--       不是「关判定」——判定照算、报告照落库，只是不拦住。
--
-- 幂等策略：
--   - 纯新增可空列，不改既有列、不回填数据；
--   - 存量库升级后 `fast_mode` 全为 NULL ⇒ 行为与改造前**逐字相同**，
--     老项目不受影响（零行为突变）；
--   - 回填/清除由作者经 PATCH /projects/{id} 完成（显式 null = 清除覆盖）。
--
-- 与 0023 / 0025 / 0029 的关系：三者落的是**进装配 payload 的项目级输入**，
-- 因此必须有各自的缓存键指纹维度；`fast_mode` 不进任何 payload（它不改装配、
-- 只改闸门判定），故**不需要**指纹维度。
-- =============================================================================

ALTER TABLE projects ADD COLUMN fast_mode INTEGER;

