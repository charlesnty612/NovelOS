-- 0030: commits.rollback_of 唯一索引改项目域（R-1 备份重导入修复，2026-09-26）
-- =============================================================================
--
-- 事故（R-1，AGENTS.md 坑区登记项）：
--   0022 步骤 0 对重复 rollback_of 的历史行追加 '#dup<rowid>' 后缀（审计行保留不删），
--   并建了**全库级**部分唯一索引 idx_commits_rollback_of ON commits(rollback_of)。
--   备份导入（backup/service.py）对不在 id 映射里的 rollback_of 值原样透传：
--   同一备份在同库导入两次时，含 #dup 后缀的行会在两个导入项目里各落一行
--   同值 rollback_of → 撞全库唯一索引 → IntegrityError，导入整体回滚，
--   备份恢复路径不可用（「备份同库重导入含 #dup 后缀项目撞唯一索引」）。
--
-- 修复（两道防线的第二道——第一道是 service 层的 #dup 剥除归一化）：
--   唯一索引改为按项目域 (project_id, rollback_of)。不变式：rollback_of 指向的
--   commit 只属于一个 project，按 (project_id, rollback_of) 唯一即保持
--   「同一 commit 至多被回滚一次」的原约束力（项目内语义不变），同时放行
--   跨项目共存（各项目对各自 commit 的回滚记录互不相干）。
--
-- 只加不改：本文件不触碰任何表结构与数据行，仅替换索引定义；
--   不修改 0022 文件本身（迁移只加不改铁律）。
-- =============================================================================

DROP INDEX IF EXISTS idx_commits_rollback_of;

CREATE UNIQUE INDEX IF NOT EXISTS idx_commits_rollback_of
    ON commits(project_id, rollback_of)
    WHERE rollback_of IS NOT NULL;

